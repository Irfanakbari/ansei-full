  private parseDateDDMMYYYY(dateStr: string): Date {
    const day = dateStr.substring(0, 2);
    const month = dateStr.substring(2, 4);
    const year = dateStr.substring(4, 8);
    return new Date(year + '-' + month + '-' + day);
  }

  private formatDate(date: Date | string | null | undefined): string {
    if (!date) return '-';
    return dayjs(date).format('DD/MM/YYYY HH:mm');
  }

  private formatDateFull(date: Date | string | null | undefined): string {
    if (!date) return '-';
    return dayjs(date).format('DD MMMM YYYY HH:mm:ss');
  }

  private getHeaderFill() {
    return {
      type: 'pattern' as const,
      pattern: 'solid' as const,
      fgColor: { argb: '1F4E79' },
    };
  }

  private getWhiteFill() {
    return {
      type: 'pattern' as const,
      pattern: 'solid' as const,
      fgColor: { argb: 'FFFFFF' },
    };
  }

  private getGrayFill() {
    return {
      type: 'pattern' as const,
      pattern: 'solid' as const,
      fgColor: { argb: 'F2F2F2' },
    };
  }

  private getSummaryFill() {
    return {
      type: 'pattern' as const,
      pattern: 'solid' as const,
      fgColor: { argb: 'D6DCE5' },
    };
  }

  private getThinBorder() {
    return {
      top: { style: 'thin' as const, color: { argb: 'CCCCCC' } },
      bottom: { style: 'thin' as const, color: { argb: 'CCCCCC' } },
      left: { style: 'thin' as const, color: { argb: 'CCCCCC' } },
      right: { style: 'thin' as const, color: { argb: 'CCCCCC' } },
    };
  }

  private getHeaderBorder() {
    return {
      top: { style: 'thin' as const, color: { argb: '000000' } },
      bottom: { style: 'thin' as const, color: { argb: '000000' } },
      left: { style: 'thin' as const, color: { argb: '000000' } },
      right: { style: 'thin' as const, color: { argb: '000000' } },
    };
  }

  private createWorkbook(
    worksheetTitle: string,
    columnWidths: number[],
  ): { workbook: Workbook; worksheet: any } {
    const workbook = new Workbook();
    workbook.creator = 'ANSEI API System';
    workbook.created = new Date();

    const worksheet = workbook.addWorksheet(worksheetTitle, {
      pageSetup: {
        paperSize: 9,
        orientation: 'landscape' as const,
        horizontalDpi: 300,
        verticalDpi: 300,
        fitToPage: true,
        fitToWidth: 1,
        fitToHeight: 0,
        margins: {
          top: 0.5,
          bottom: 0.5,
          left: 0.5,
          right: 0.5,
          header: 0.3,
          footer: 0.3,
        },
      },
      headerFooter: {
        firstHeader: '&"Calibri,Bold"&14ANSEI Production System',
        firstFooter: '&"Calibri"&10Page &P of &N',
        oddFooter:
          '&"Calibri"&10Page &P of &N | Generated by ANSEI System at &D',
      },
    });

    columnWidths.forEach((width, index) => {
      worksheet.getColumn(index + 1).width = width;
    });

    return { workbook, worksheet };
  }

  private setupReportHeader(
    worksheet: any,
    reportTitle: string,
    colCount: number,
    fromDate?: string,
    toDate?: string,
  ): void {
    const lastCol =
      worksheet.getColumn(colCount).letter ||
      String.fromCharCode(64 + colCount);
    worksheet.addRow([]);
    worksheet.mergeCells('A2:' + lastCol + '2');
    const titleCell = worksheet.getCell('A2');
    titleCell.value = reportTitle;
    titleCell.font = {
      name: 'Calibri',
      size: 18,
      bold: true,
      color: { argb: '1F4E79' },
    };
    titleCell.alignment = {
      horizontal: 'center' as const,
      vertical: 'middle' as const,
    };
    worksheet.mergeCells('A3:' + lastCol + '3');
    const subtitleCell = worksheet.getCell('A3');
    const fromFormatted = fromDate
      ? fromDate.substring(0, 2) +
        '/' +
        fromDate.substring(2, 4) +
        '/' +
        fromDate.substring(4, 8)
      : '-';
    const toFormatted = toDate
      ? toDate.substring(0, 2) +
        '/' +
        toDate.substring(2, 4) +
        '/' +
        toDate.substring(4, 8)
      : '-';
    subtitleCell.value =
      'Period: ' +
      fromFormatted +
      ' to ' +
      toFormatted +
      ' | Generated: ' +
      this.formatDateFull(new Date()) +
      ' | ANSEI Production System';
    subtitleCell.font = {
      name: 'Calibri',
      size: 11,
      color: { argb: '666666' },
    };
    subtitleCell.alignment = {
      horizontal: 'center' as const,
      vertical: 'middle' as const,
    };
    worksheet.addRow([]);
  }

  private addColumnHeaders(worksheet: any, headers: string[]): any {
    const headerRow = worksheet.addRow(headers);
    headerRow.height = 30;
    const headerFill = this.getHeaderFill();
    const headerBorder = this.getHeaderBorder();
    headerRow.eachCell((cell: any) => {
      cell.font = {
        name: 'Calibri',
        size: 11,
        bold: true,
        color: { argb: 'FFFFFF' },
      };
      cell.fill = headerFill;
      cell.alignment = {
        horizontal: 'center' as const,
        vertical: 'middle' as const,
        wrapText: true,
      };
      cell.border = headerBorder;
    });
    return headerRow;
  }

  private addDataRow(
    worksheet: any,
    values: any[],
    rowIndex: number,
    numberColumns: number[] = [],
  ): void {
    const row = worksheet.addRow(values);
    row.height = 20;
    const isEven = rowIndex % 2 === 0;
    const fill = isEven ? this.getGrayFill() : this.getWhiteFill();
    const thinBorder = this.getThinBorder();
    row.eachCell((cell: any, colNumber: number) => {
      cell.font = { name: 'Calibri', size: 10 };
      cell.fill = fill;
      cell.border = thinBorder;
      if (numberColumns.includes(colNumber)) {
        cell.alignment = {
          horizontal: 'right' as const,
          vertical: 'middle' as const,
        };
      } else if (colNumber === 1) {
        cell.alignment = {
          horizontal: 'center' as const,
          vertical: 'middle' as const,
        };
      } else {
        cell.alignment = {
          horizontal: 'left' as const,
          vertical: 'middle' as const,
        };
      }
    });
  }

  private addSummaryRow(
    worksheet: any,
    values: any[],
    numberColumns: number[],
  ): void {
    const row = worksheet.addRow(values);
    row.height = 25;
    const summaryFill = this.getSummaryFill();
    row.eachCell((cell: any) => {
      cell.font = { name: 'Calibri', size: 11, bold: true };
      cell.fill = summaryFill;
      cell.border = {
        top: { style: 'medium' as const, color: { argb: '1F4E79' } },
        bottom: { style: 'medium' as const, color: { argb: '1F4E79' } },
        left: { style: 'thin' as const, color: { argb: 'CCCCCC' } },
        right: { style: 'thin' as const, color: { argb: 'CCCCCC' } },
      };
    });
  }

  private finalizeWorksheet(worksheet: any, dataRowCount: number): void {
    if (dataRowCount > 0) {
      worksheet.views = [
        { state: 'frozen' as const, xSplit: 0, ySplit: 5, activeCell: 'A6' },
      ];
      const colCount = worksheet.columnCount || 10;
      worksheet.autoFilter = {
        from: { row: 5, column: 1 },
        to: { row: 5, column: colCount },
      };
    }
  }

  private async writeBuffer(workbook: Workbook): Promise<Buffer> {
    const buffer = await workbook.xlsx.writeBuffer();
    return Buffer.from(buffer as any);
  }

