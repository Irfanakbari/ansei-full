  async generateInventoryLedgerReport(
    fromdate?: string,
    todate?: string,
    category?: string,
    location?: string,
  ): Promise<Buffer> {
    const colWidths = [6, 18, 14, 18, 18, 16, 20, 22, 14, 12, 12, 14, 30, 18];
    const { workbook, worksheet } = this.createWorkbook(
      'Inventory Ledger',
      colWidths,
    );
    this.setupReportHeader(
      worksheet,
      'INVENTORY LEDGER REPORT',
      colWidths.length,
      fromdate,
      todate,
    );
    const headers = [
      'No.',
      'Transaction Date',
      'Item Category',
      'Material Part Number',
      'Finish Good Part Number',
      'Location',
      'Transaction Type',
      'Reference Doc',
      'Balance Before',
      'Qty In',
      'Qty Out',
      'Balance After',
      'Notes',
      'Created By',
    ];
    this.addColumnHeaders(worksheet, headers);
    const whereClause: any = {};
    if (fromdate || todate) {
      whereClause.TransactionDate = {};
      if (fromdate) {
        const from = this.parseDateDDMMYYYY(fromdate);
        from.setHours(0, 0, 0, 0);
        whereClause.TransactionDate.gte = from;
      }
      if (todate) {
        const to = this.parseDateDDMMYYYY(todate);
        to.setHours(23, 59, 59, 999);
        whereClause.TransactionDate.lte = to;
      }
    }
    if (category) whereClause.ItemCategory = category as any;
    if (location) whereClause.Location = location as any;
    const ledgers = await this.prisma.inventoryLedger.findMany({
      where: whereClause,
      include: { MaterialData: true, FGData: true },
      orderBy: { TransactionDate: 'desc' },
    });
    let grandTotalIn = 0,
      grandTotalOut = 0;
    ledgers.forEach((l, index) => {
      grandTotalIn += l.QtyIn || 0;
      grandTotalOut += l.QtyOut || 0;
      this.addDataRow(
        worksheet,
        [
          index + 1,
          this.formatDate(l.TransactionDate),
          l.ItemCategory,
          l.ItemCategory === ItemCategory.MATERIAL
            ? l.MaterialData?.PartNumber || l.MaterialId
            : '-',
          l.ItemCategory === ItemCategory.FINISH_GOOD
            ? l.FGData?.PartNumber || l.FinishGoodId
            : '-',
          l.Location,
          l.TransactionType,
          l.ReferenceDoc,
          l.BalanceBefore,
          l.QtyIn || 0,
          l.QtyOut || 0,
          l.BalanceAfter,
          l.Notes || '-',
          l.CreatedBy,
        ],
        index,
        [9, 10, 11, 12],
      );
    });
    this.addSummaryRow(
      worksheet,
      [
        '',
        '',
        '',
        '',
        '',
        '',
        '',
        'GRAND TOTAL',
        '',
        grandTotalIn,
        grandTotalOut,
        '',
        '',
        '',
      ],
      [10, 11],
    );
    this.finalizeWorksheet(worksheet, ledgers.length);
    return this.writeBuffer(workbook);
  }
