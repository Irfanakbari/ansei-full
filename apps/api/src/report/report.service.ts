  async generateStockMaterialReport(): Promise<Buffer> {
    const colWidths = [6, 18, 30, 20, 15, 10, 12, 14, 12];
    const { workbook, worksheet } = this.createWorkbook(
      'Stock Material',
      colWidths,
    );
    this.setupReportHeader(
      worksheet,
      'STOCK MATERIAL REPORT',
      colWidths.length,
    );
    const headers = [
      'No.',
      'Part Number',
      'Part Name',
      'Supplier',
      'Rack Location',
      'Satuan',
      'Qty Rack',
      'Qty Warehouse',
      'Total Stock',
    ];
    this.addColumnHeaders(worksheet, headers);
    const materials = await this.prisma.material.findMany({
      where: { IsActive: true },
      include: { SatuanData: true },
      orderBy: { PartNumber: 'asc' },
    });
    let grandTotalRack = 0,
      grandTotalWarehouse = 0;
    materials.forEach((m, index) => {
      const qtyRack = m.QtyRack || 0,
        qtyWarehouse = m.QtyWarehouse || 0;
      grandTotalRack += qtyRack;
      grandTotalWarehouse += qtyWarehouse;
      this.addDataRow(
        worksheet,
        [
          index + 1,
          m.PartNumber,
          m.PartName,
          m.Supplier || '-',
          m.RackLocation || '-',
          m.SatuanData?.Name || '-',
          qtyRack,
          qtyWarehouse,
          qtyRack + qtyWarehouse,
        ],
        index,
        [7, 8, 9],
      );
    });
    this.addSummaryRow(
      worksheet,
      [
        '',
        '',
        '',
        '',
        '',
        'GRAND TOTAL',
        grandTotalRack,
        grandTotalWarehouse,
        grandTotalRack + grandTotalWarehouse,
      ],
      [7, 8, 9],
    );
    this.finalizeWorksheet(worksheet, materials.length);
    return this.writeBuffer(workbook);
  }

  async generateIncomingWarehouseReport(
    fromdate?: string,
    todate?: string,
  ): Promise<Buffer> {
    const colWidths = [6, 18, 18, 22, 18, 18, 18, 28, 12, 12];
    const { workbook, worksheet } = this.createWorkbook(
      'Incoming Warehouse',
      colWidths,
    );
    this.setupReportHeader(
      worksheet,
      'INCOMING WAREHOUSE REPORT',
      colWidths.length,
      fromdate,
      todate,
    );
    const headers = [
      'No.',
      'Incoming ID',
      'PO Number',
      'Supplier Name',
      'Received Date',
      'Received By',
      'Part Number',
      'Part Name',
      'Qty Ordered',
      'Qty Checked',
    ];
    this.addColumnHeaders(worksheet, headers);
    const whereClause: any = {};
    if (fromdate || todate) {
      whereClause.CreatedAt = {};
      if (fromdate) {
        const from = this.parseDateDDMMYYYY(fromdate);
        from.setHours(0, 0, 0, 0);
        whereClause.CreatedAt.gte = from;
      }
      if (todate) {
        const to = this.parseDateDDMMYYYY(todate);
        to.setHours(23, 59, 59, 999);
        whereClause.CreatedAt.lte = to;
      }
    }
    const incomings = await this.prisma.incoming.findMany({
      where: whereClause,
      include: {
        SupplierData: true,
        IncomingMaterial: { include: { MaterialData: true } },
      },
      orderBy: { CreatedAt: 'desc' },
    });
    const data: any[] = [];
    incomings.forEach((incoming) => {
      if (incoming.IncomingMaterial.length === 0) {
        data.push({
          incomingId: incoming.Id,
          poId: incoming.PoId,
          supplierName: incoming.SupplierData?.Name || '-',
          createdAt: incoming.CreatedAt,
          receivedBy: incoming.ReceivedBy,
          partNumber: '-',
          partName: '-',
          qty: 0,
          qtyChecked: 0,
        });
      } else {
        incoming.IncomingMaterial.forEach((mat) => {
          data.push({
            incomingId: incoming.Id,
            poId: incoming.PoId,
            supplierName: incoming.SupplierData?.Name || '-',
            createdAt: incoming.CreatedAt,
            receivedBy: incoming.ReceivedBy,
            partNumber: mat.MaterialData?.PartNumber || mat.MaterialId,
            partName: mat.MaterialData?.PartName || '-',
            qty: mat.Qty,
            qtyChecked: mat.QtyChecked,
          });
        });
      }
    });
    let grandTotalQty = 0,
      grandTotalChecked = 0;
    data.forEach((row, index) => {
      grandTotalQty += row.qty;
      grandTotalChecked += row.qtyChecked;
      this.addDataRow(
        worksheet,
        [
          index + 1,
          row.incomingId,
          row.poId,
          row.supplierName,
          this.formatDate(row.createdAt),
          row.receivedBy,
          row.partNumber,
          row.partName,
          row.qty,
          row.qtyChecked,
        ],
        index,
        [9, 10],
      );
    });
    this.addSummaryRow(
      worksheet,
      ['', '', '', '', '', '', '', '', 'GRAND TOTAL', grandTotalChecked],
      [9, 10],
    );
    this.finalizeWorksheet(worksheet, data.length);
    return this.writeBuffer(workbook);
  }

